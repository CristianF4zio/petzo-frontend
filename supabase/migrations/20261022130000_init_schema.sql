-- Petzo core schema (SPEC §14)

create type user_role as enum ('user', 'admin');
create type account_type as enum ('person', 'foundation');
create type verification_status as enum ('none', 'pending', 'verified', 'rejected');
create type plan_type as enum ('free', 'pro');
create type pet_species as enum ('dog', 'cat');
create type pet_sex as enum ('male', 'female');
create type pet_size as enum ('small', 'medium', 'large');
create type pet_status as enum ('draft', 'pending_review', 'approved', 'rejected', 'paused', 'adopted');
create type pet_source as enum ('app', 'instagram');
create type request_status as enum ('pending', 'approved', 'rejected', 'withdrawn');
create type report_status as enum ('open', 'resolved');
create type ai_task as enum ('moderation', 'pre_evaluation', 'match', 'import');
create type import_status as enum ('queued', 'running', 'done', 'failed');

create function set_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table municipalities (
  id smallint generated by default as identity primary key,
  name text not null unique,
  state text not null,
  created_at timestamptz not null default now()
);

create table profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text,
  avatar_url text,
  whatsapp text,
  municipality_id smallint references municipalities (id),
  role user_role not null default 'user',
  account_type account_type not null default 'person',
  foundation_name text,
  foundation_instagram text,
  foundation_bio text,
  verification_status verification_status not null default 'none',
  plan plan_type not null default 'free',
  is_suspended boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table lifestyle_profiles (
  user_id uuid primary key references profiles (id) on delete cascade,
  answers jsonb not null,
  created_at timestamptz not null default now()
);

create table pets (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references profiles (id) on delete cascade,
  species pet_species not null,
  name text not null,
  age_months smallint check (age_months >= 0),
  sex pet_sex not null,
  size pet_size not null,
  municipality_id smallint not null references municipalities (id),
  vaccinated boolean not null default false,
  sterilized boolean not null default false,
  description text,
  status pet_status not null default 'pending_review',
  moderation_reason text,
  risk_score smallint check (risk_score between 0 and 100),
  source pet_source not null default 'app',
  source_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index pets_owner_id_idx on pets (owner_id);
create index pets_catalog_idx on pets (status, species, size, municipality_id);

create table pet_photos (
  id uuid primary key default gen_random_uuid(),
  pet_id uuid not null references pets (id) on delete cascade,
  storage_path text not null,
  position smallint not null default 0,
  created_at timestamptz not null default now()
);

create index pet_photos_pet_id_idx on pet_photos (pet_id, position);

create table adoption_requests (
  id uuid primary key default gen_random_uuid(),
  pet_id uuid not null references pets (id) on delete cascade,
  adopter_id uuid not null references profiles (id) on delete cascade,
  status request_status not null default 'pending',
  answers jsonb,
  motivation text not null,
  ai_summary text,
  ai_score smallint check (ai_score between 0 and 100),
  decided_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- one active request per pet and adopter (HU-07)
create unique index adoption_requests_one_pending_idx
  on adoption_requests (pet_id, adopter_id) where status = 'pending';
create index adoption_requests_adopter_id_idx on adoption_requests (adopter_id);

create table favorites (
  user_id uuid not null references profiles (id) on delete cascade,
  pet_id uuid not null references pets (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, pet_id)
);

create table reports (
  id uuid primary key default gen_random_uuid(),
  pet_id uuid not null references pets (id) on delete cascade,
  reporter_id uuid not null references profiles (id) on delete cascade,
  reason text not null,
  status report_status not null default 'open',
  created_at timestamptz not null default now()
);

-- polymorphic on purpose: entity_type + entity_id, no FK (SPEC §13)
create table ai_logs (
  id uuid primary key default gen_random_uuid(),
  task ai_task not null,
  entity_type text,
  entity_id uuid,
  model text not null,
  input_tokens integer not null default 0,
  output_tokens integer not null default 0,
  result jsonb,
  created_at timestamptz not null default now()
);

-- daily cap sums tokens by created_at
create index ai_logs_created_at_idx on ai_logs (created_at);

create table import_jobs (
  id uuid primary key default gen_random_uuid(),
  instagram_handle text not null,
  requested_by uuid references profiles (id) on delete set null,
  status import_status not null default 'queued',
  pets_created integer not null default 0,
  error text,
  created_at timestamptz not null default now()
);

create trigger profiles_updated_at before update on profiles
  for each row execute function set_updated_at();
create trigger pets_updated_at before update on pets
  for each row execute function set_updated_at();
create trigger adoption_requests_updated_at before update on adoption_requests
  for each row execute function set_updated_at();
